"""Generate src/mimic_omop/cdm/spec.py from the OHDSI CDM field-level specification.

Usage: uv run python scripts/gen_cdm_spec.py
"""

import csv
import io
import urllib.request
from pathlib import Path

CDM_VERSION = "5.5"
REF = "v5.5.0"  # OHDSI/CommonDataModel release tag, commit ba3dc1b651cc, 2026-08-25
URL = (
    "https://raw.githubusercontent.com/OHDSI/CommonDataModel/"
    f"{REF}/inst/csv/OMOP_CDMv{CDM_VERSION}_Field_Level.csv"
)
OUT = Path(__file__).parents[1] / "src" / "mimic_omop" / "cdm" / "spec.py"


def main() -> None:
    with urllib.request.urlopen(URL) as resp:
        rows = list(csv.DictReader(io.StringIO(resp.read().decode("utf-8"))))

    tables: dict[str, list[str]] = {}
    for r in rows:
        args = [repr(r["cdmFieldName"]), repr(r["cdmDatatype"].lower())]
        if r["isRequired"].upper() == "TRUE":
            args.append("required=True")
        if r["isPrimaryKey"].upper() == "TRUE":
            args.append("pk=True")
        if r["isForeignKey"].upper() == "TRUE":
            args.append(f"fk=({r['fkTableName'].lower()!r}, {r['fkFieldName'].lower()!r})")
        tables.setdefault(r["cdmTableName"].lower(), []).append(
            f"        Field({', '.join(args)}),"
        )

    lines = [
        f'"""OMOP CDM {CDM_VERSION} table specification.\n\n'
        f"Generated by scripts/gen_cdm_spec.py from OHDSI/CommonDataModel@{REF}. Do not edit.\n"
        '"""',
        "",
        "from mimic_omop.cdm.field import Field",
        "",
        f"CDM_VERSION = {CDM_VERSION!r}",
        "",
        "TABLES: dict[str, tuple[Field, ...]] = {",
    ]
    for table, fields in tables.items():
        lines += [f"    {table!r}: (", *fields, "    ),"]
    lines += ["}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(tables)} tables, {len(rows)} fields)")


if __name__ == "__main__":
    main()
