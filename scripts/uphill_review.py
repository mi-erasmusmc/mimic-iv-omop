"""Write the review list of CVB codes mapped to a broader concept (review R29):
docs/uphill-review.md (a summary per CVB set and the most frequent codes) and
docs/uphill-review.csv (all of them).

Usage: uv run python scripts/uphill_review.py <vocab dir> <accounting dir> [docs dir]

Rows are the source rows of the code in the tables its CVB set maps (from the E1 accounting).
Codes of sets mapped only where Athena does not map the code (ICD, HCPCS) may be used for fewer
rows than counted. Counts from 1 to 9 are written as "<10" (SMALL), since the files are published.
"""

import sys
from pathlib import Path

import polars as pl

from mimic_omop.vocab import Vocab

TOP = 100
SMALL = 10


def count(n: int | None) -> str:
    return f"<{SMALL}" if n and n < SMALL else f"{n or 0:,}"


# CVB code set -> the E1 sources whose codes it maps
SET_SOURCES = {
    "mimiciv_icu.d_items.label": ["chartevents", "procedureevents", "datetimeevents"],
    "mimiciv_icu.chartevents.itemid": ["chartevents"],
    "mimiciv_icu.inputevents.itemid": ["inputevents"],
    "mimiciv_icu.outputevents.itemid": ["outputevents"],
    "mimiciv_icu.procedureevents.itemid": ["procedureevents"],
    "mimiciv_icu.datetimeevents.itemid": ["datetimeevents"],
    "mimiciv_hosp.d_labitems.itemid": ["labevents"],
    "mimiciv_hosp.labevents.itemid": ["labevents"],
    "mimiciv_hosp.prescriptions.drug": ["prescriptions", "emar"],
    "mimiciv_hosp.d_icd_diagnoses.icd_code": ["diagnoses_icd", "ed_diagnosis"],
    "mimiciv_hosp.d_icd_procedures.icd_code": ["procedures_icd"],
    "mimiciv_hosp.d_hcpcs.code": ["hcpcsevents"],
    "mimiciv_hosp.microbiologyevents.test_itemid": ["microbiologyevents"],
    "mimiciv_hosp.microbiologyevents.ab_itemid": ["microbiologyevents"],
}


def main(vocab_dir: Path, accounting_dir: Path, docs: Path) -> None:
    vocab = Vocab(vocab_dir)
    uphill = (
        vocab.cvb()
        .filter(pl.col("relationship_id") == "Maps to", pl.col("predicate_id") == "skos:broadMatch")
        .select(
            "source_code_set",
            "source_code",
            label=pl.col("source_description"),
            target_concept_id=pl.col("target_concept_id").cast(pl.Int64),
        )
        .collect()
    )
    names = vocab.athena("concept").select(
        target_concept_id="concept_id",
        target_name="concept_name",
        target_domain="domain_id",
        target_class="concept_class_id",
    )
    codes = pl.read_parquet(accounting_dir / "codes.parquet")
    codes = codes.select("source", "code", "source_rows")
    sources = pl.DataFrame(
        [(s, src) for s, srcs in SET_SOURCES.items() for src in srcs],
        schema=["source_code_set", "source"],
        orient="row",
    )
    rows = (
        uphill.select("source_code_set", "source_code")
        .unique()
        .join(sources, on="source_code_set", how="left")
        .join(codes, left_on=["source", "source_code"], right_on=["source", "code"], how="left")
        .group_by("source_code_set", "source_code")
        .agg(rows=pl.col("source_rows").sum())
    )
    table = (
        uphill.join(names.collect(), on="target_concept_id", how="left")
        .join(rows, on=["source_code_set", "source_code"], how="left")
        .sort(
            ["rows", "source_code_set", "source_code", "target_concept_id"],
            descending=[True, False, False, False],
            nulls_last=True,
        )
    )
    small = pl.col("rows").is_between(1, SMALL - 1)
    table.with_columns(
        rows=pl.when(small).then(pl.lit(f"<{SMALL}")).otherwise(pl.col("rows").cast(pl.String))
    ).write_csv(docs / "uphill-review.csv")

    per_set = (
        table.unique(["source_code_set", "source_code"])
        .group_by("source_code_set")
        .agg(codes=pl.len(), rows=pl.col("rows").sum())
        .sort(["rows", "source_code_set"], descending=[True, False])
    )
    top_codes = (
        table.unique(["source_code_set", "source_code"], keep="first", maintain_order=True)
        .head(TOP)
        .select("source_code_set", "source_code")
    )
    top = table.join(top_codes, on=["source_code_set", "source_code"], how="semi")

    def cell(v) -> str:
        return "" if v is None else str(v).replace("|", "\\|")

    lines = [
        "# Codes mapped to a broader concept: review list",
        "",
        "Generated by `scripts/uphill_review.py` from CVB, Athena and the E1 accounting of",
        "MIMIC-IV 3.1. These are the CVB codes without an equivalent ('Maps to') that the ETL",
        "maps to the concept CVB records them `Is a`",
        "([review R29](review.md#r29-cvb-items-mapped-only-to-a-broader-concept)). A wrong `Is a`",
        "becomes a wrong record, so they are worth a mapping expert's look, most frequent first;",
        "a relationship found wrong goes into",
        "`src/mimic_omop/mappings/cvb_exclusions.csv` and to CVB",
        "([R26](review.md#r26-feedback-for-cvb)). All codes are in `uphill-review.csv`.",
        "",
        f"{table.select('source_code_set', 'source_code').n_unique():,} codes, "
        f"{table.height:,} targets. Rows are the code's source rows in the tables its set maps.",
        "",
        "| CVB set | Codes | Rows |",
        "|---|---:|---:|",
        *(f"| `{s}` | {c:,} | {count(r)} |" for s, c, r in per_set.iter_rows()),
        "",
        f"## The {TOP} most frequent codes",
        "",
        "| CVB set | Code | Label | Rows | Broader concept | Domain |",
        "|---|---|---|---:|---|---|",
        *(
            f"| {cell(r['source_code_set'].removeprefix('mimiciv_'))} | {cell(r['source_code'])} "
            f"| {cell(r['label'])} | {count(r['rows'])} | {cell(r['target_concept_id'])} "
            f"{cell(r['target_name'])} | {cell(r['target_domain'])} |"
            for r in top.iter_rows(named=True)
        ),
        "",
    ]
    (docs / "uphill-review.md").write_text("\n".join(lines))
    print(per_set)


if __name__ == "__main__":
    args = sys.argv[1:]
    main(Path(args[0]), Path(args[1]), Path(args[2]) if len(args) > 2 else Path("docs"))
